-- Owner-Werbung: Bildbibliothek für den Design-Agenten – 13.11.2026
-- Bilder liegen im vorhandenen privaten Bucket „owner-marketing“ (Ordner library/). Nur Plattform-Inhaber.

create table if not exists public.owner_marketing_images (
  id bigint generated by default as identity primary key,
  path text not null unique,
  description text,
  tags text[] not null default '{}',
  realistic boolean not null default false,
  ai_generated boolean not null default true,
  width int,
  height int,
  last_used_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists owner_marketing_images_created_idx on public.owner_marketing_images (created_at desc);

alter table public.owner_marketing_images enable row level security;
drop policy if exists owner_marketing_images_all on public.owner_marketing_images;
create policy owner_marketing_images_all on public.owner_marketing_images for all to authenticated
  using (public.current_role_id() = 1) with check (public.current_role_id() = 1);
grant select, insert, update, delete on public.owner_marketing_images to authenticated;

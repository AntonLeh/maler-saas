create table if not exists public.owner_articles (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 80),
  keyword text not null default '',
  title text not null,
  meta_title text not null default '',
  meta_description text not null default '',
  intro text not null default '',
  body text not null default '',
  faq jsonb not null default '[]'::jsonb,
  related_pages text[] not null default '{}',
  status text not null default 'entwurf' check (status in ('entwurf', 'veroeffentlicht')),
  reason text,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.owner_articles enable row level security;
drop policy if exists owner_articles_all on public.owner_articles;
create policy owner_articles_all on public.owner_articles for all to authenticated
  using (public.current_role_id() = 1) with check (public.current_role_id() = 1);
grant select, insert, update, delete on public.owner_articles to authenticated;

-- Öffentlich: Liste der veröffentlichten Artikel
create or replace function public.ratgeber_list()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(jsonb_agg(jsonb_build_object('slug', a.slug, 'title', a.title, 'intro', a.intro, 'published_at', a.published_at, 'updated_at', a.updated_at) order by a.published_at desc), '[]'::jsonb)
  from public.owner_articles a where a.status = 'veroeffentlicht';
$$;

-- Öffentlich: ein veröffentlichter Artikel
create or replace function public.ratgeber_get(p_slug text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select to_jsonb(x) from (
    select a.slug, a.title, a.meta_title, a.meta_description, a.intro, a.body, a.faq, a.related_pages, a.published_at, a.updated_at
    from public.owner_articles a
    where a.status = 'veroeffentlicht' and a.slug = lower(left(coalesce(p_slug, ''), 80))
  ) x;
$$;

revoke all on function public.ratgeber_list() from public;
revoke all on function public.ratgeber_get(text) from public;
grant execute on function public.ratgeber_list() to anon, authenticated;
grant execute on function public.ratgeber_get(text) to anon, authenticated;

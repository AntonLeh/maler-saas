-- Nachweise von Subunternehmern und Leiharbeitsfirmen (z. B. § 48b) – 12.11.2026
-- Nur der Inhaber/Admin des Betriebs sieht und verwaltet die Nachweise.

create table if not exists public.partner_documents (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null,
  user_id bigint not null references public.app_users (id) on delete cascade,
  doc_type text not null check (char_length(doc_type) between 1 and 40),
  title text,
  valid_until date,
  file_path text,
  file_name text,
  note text,
  created_by bigint,
  created_at timestamptz not null default now()
);
create index if not exists partner_documents_tenant_idx on public.partner_documents (tenant_id, user_id);

alter table public.partner_documents enable row level security;

drop policy if exists partner_documents_admin on public.partner_documents;
create policy partner_documents_admin on public.partner_documents for all to authenticated
  using (public.current_role_id() = 2 and tenant_id = public.current_tenant_id())
  with check (
    public.current_role_id() = 2
    and tenant_id = public.current_tenant_id()
    and exists (select 1 from public.app_users u where u.id = user_id and u.tenant_id = partner_documents.tenant_id)
  );

grant select, insert, update, delete on public.partner_documents to authenticated;

-- ---------- Speicher (privat, Ordner = Betrieb) ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('partner-docs', 'partner-docs', false, 10485760, array['image/jpeg', 'image/png', 'image/webp', 'application/pdf'])
on conflict (id) do update set public = false, file_size_limit = 10485760,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp', 'application/pdf'];

drop policy if exists partner_docs_admin_insert on storage.objects;
create policy partner_docs_admin_insert on storage.objects
  for insert to authenticated
  with check (bucket_id = 'partner-docs' and public.current_role_id() = 2
    and (storage.foldername(name))[1] = public.current_tenant_id()::text);

drop policy if exists partner_docs_admin_read on storage.objects;
create policy partner_docs_admin_read on storage.objects
  for select to authenticated
  using (bucket_id = 'partner-docs' and public.current_role_id() = 2
    and (storage.foldername(name))[1] = public.current_tenant_id()::text);

drop policy if exists partner_docs_admin_delete on storage.objects;
create policy partner_docs_admin_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'partner-docs' and public.current_role_id() = 2
    and (storage.foldername(name))[1] = public.current_tenant_id()::text);

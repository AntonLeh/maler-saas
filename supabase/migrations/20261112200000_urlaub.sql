-- ---------- Feiertage: Bundesland / Region ----------
alter table public.company_settings add column if not exists holiday_region text;

-- ---------- Urlaubsanspruch je Person (nur Inhaber/Admin) ----------
create table if not exists public.employee_leave (
  user_id bigint primary key references public.app_users (id) on delete cascade,
  tenant_id bigint not null,
  vacation_days numeric(5, 1) check (vacation_days is null or (vacation_days >= 0 and vacation_days <= 60)),
  work_weekdays smallint[] not null default '{1,2,3,4,5}',
  entry_date date,
  years jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create index if not exists employee_leave_tenant_idx on public.employee_leave (tenant_id);
alter table public.employee_leave enable row level security;

drop policy if exists employee_leave_admin on public.employee_leave;
create policy employee_leave_admin on public.employee_leave for all to authenticated
  using (public.current_role_id() = 2 and tenant_id = public.current_tenant_id())
  with check (
    public.current_role_id() = 2
    and tenant_id = public.current_tenant_id()
    and exists (select 1 from public.app_users u where u.id = user_id and u.tenant_id = employee_leave.tenant_id)
  );
grant select, insert, update, delete on public.employee_leave to authenticated;

-- ---------- Abwesenheiten ----------
create table if not exists public.absences (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null,
  user_id bigint not null references public.app_users (id) on delete cascade,
  kind text not null check (kind in ('urlaub', 'krank', 'kind_krank', 'berufsschule', 'sonderurlaub', 'unbezahlt', 'ueberstunden', 'schlechtwetter')),
  start_date date not null,
  end_date date not null,
  start_half boolean not null default false,
  end_half boolean not null default false,
  au_present boolean not null default false,
  note text,
  status text not null default 'genehmigt' check (status in ('beantragt', 'genehmigt', 'abgelehnt')),
  created_by bigint,
  created_at timestamptz not null default now(),
  decided_by bigint,
  decided_at timestamptz,
  constraint absences_dates_check check (end_date >= start_date and end_date - start_date <= 400)
);
create index if not exists absences_tenant_idx on public.absences (tenant_id, start_date);
create index if not exists absences_user_idx on public.absences (user_id, start_date);
alter table public.absences enable row level security;

-- Inhaber/Admin: alles im eigenen Betrieb
drop policy if exists absences_admin on public.absences;
create policy absences_admin on public.absences for all to authenticated
  using (public.current_role_id() = 2 and tenant_id = public.current_tenant_id())
  with check (
    public.current_role_id() = 2
    and tenant_id = public.current_tenant_id()
    and exists (select 1 from public.app_users u where u.id = user_id and u.tenant_id = absences.tenant_id)
  );

-- Jeder sieht seine eigenen Abwesenheiten (für die Mitarbeiter-App, Teil B)
drop policy if exists absences_own_read on public.absences;
create policy absences_own_read on public.absences for select to authenticated
  using (user_id = public.current_app_user_id());

grant select, insert, update, delete on public.absences to authenticated;

-- ---------- Projektleiter: wer ist wann abwesend (ohne Grund) ----------
create or replace function public.team_absences(p_from date, p_to date)
returns table (user_id bigint, start_date date, end_date date, start_half boolean, end_half boolean)
language sql
stable
security definer
set search_path = public
as $$
  select a.user_id, a.start_date, a.end_date, a.start_half, a.end_half
  from public.absences a
  where a.tenant_id = public.current_tenant_id()
    and public.current_role_id() in (2, 3)
    and a.status = 'genehmigt'
    and a.start_date <= p_to
    and a.end_date >= p_from;
$$;
revoke all on function public.team_absences(date, date) from public, anon;
grant execute on function public.team_absences(date, date) to authenticated;

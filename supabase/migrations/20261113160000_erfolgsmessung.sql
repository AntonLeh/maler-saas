-- ---------- Kurzlinks ----------
alter table public.owner_marketing_posts add column if not exists short_code text;
create unique index if not exists owner_marketing_posts_short_code_idx on public.owner_marketing_posts (short_code) where short_code is not null;
alter table public.owner_marketing_posts drop constraint if exists owner_marketing_posts_short_code_check;
alter table public.owner_marketing_posts add constraint owner_marketing_posts_short_code_check check (short_code is null or short_code ~ '^[a-z0-9]{3,24}$');

-- Kurzlink auflösen (für Besucher ohne Anmeldung): liefert nur die Kampagnen-Kennung
create or replace function public.resolve_short_link(p_code text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select p.utm_campaign from public.owner_marketing_posts p
  where p.short_code = lower(left(coalesce(p_code, ''), 24))
  limit 1;
$$;
revoke all on function public.resolve_short_link(text) from public;
grant execute on function public.resolve_short_link(text) to anon, authenticated;

-- ---------- Herkunft der Registrierungen (nur Plattform-Inhaber) ----------
create or replace function public.owner_signup_origins()
returns table (tenant_id bigint, origin jsonb)
language sql
stable
security definer
set search_path = public
as $$
  select distinct on (u.tenant_id) u.tenant_id::bigint, au.raw_user_meta_data -> 'signup_origin'
  from public.app_users u
  join auth.users au on au.id = u.auth_user_id
  where exists (select 1 from public.app_users o where o.auth_user_id = auth.uid() and o.role_id = 1)
    and au.raw_user_meta_data ->> 'signup_type' = 'company'
  order by u.tenant_id, au.created_at;
$$;
revoke all on function public.owner_signup_origins() from public, anon;
grant execute on function public.owner_signup_origins() to authenticated;

-- ---------- Werbekosten (von Hand, später automatisch) ----------
create table if not exists public.owner_ad_costs (
  id bigint generated by default as identity primary key,
  campaign text not null check (char_length(campaign) between 1 and 80),
  channel text not null default 'facebook',
  period_from date,
  period_to date,
  amount numeric(10, 2) not null check (amount >= 0 and amount < 1000000),
  note text,
  created_at timestamptz not null default now()
);
alter table public.owner_ad_costs enable row level security;
drop policy if exists owner_ad_costs_all on public.owner_ad_costs;
create policy owner_ad_costs_all on public.owner_ad_costs for all to authenticated
  using (public.current_role_id() = 1) with check (public.current_role_id() = 1);
grant select, insert, update, delete on public.owner_ad_costs to authenticated;
